"""Refresh vendored xrt sources, SDK shims and imports as one recorded snapshot.

python tools/sync_xrt.py --source ../xrt
python tools/sync_xrt.py --source ../xrt --ref COMMIT
python tools/sync_xrt.py --check

Upstream files are copied byte-for-byte. The lock records working-tree hashes
as well as HEAD: an uncommitted upstream snapshot is never labelled a release.
The generated registry/shims/imports are xs integration code, not upstream patches.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import tempfile
from pathlib import Path, PurePosixPath

from xs_extensions import ROOT, REGISTRY, load_registry

LOCK = ROOT / "lib/xrt_sources.lock.json"
# xruntime is xlang's typed language runtime, not an xs deployment extension.
EXCLUDED_LIBRARIES = frozenset({"xruntime"})


def library_names(directory: Path) -> tuple[str, ...]:
    return tuple(p.parent.parent.name for p in sorted(directory.glob("*/config/modules.json"))
                 if p.parent.parent.name not in EXCLUDED_LIBRARIES)


LIBRARIES = library_names(ROOT / "lib")


def symbol_prefix(name: str, manifest: dict) -> str:
    if name == "xacme":
        return "(?:xrt|xacme)"
    if name == "xllm-session":
        return "xllm"
    prefix = manifest["api_reference"]["function_prefix"]
    if not re.fullmatch(r"[A-Za-z_]\w*", prefix):
        raise ValueError(f"{name}: invalid public function prefix")
    return prefix


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def without_comments(text: str) -> str:
    return re.sub(r"//[^\r\n]*", " ",
                  re.sub(r"/\*.*?\*/", " ", text, flags=re.S))


def public_functions_text(headers: list[str], prefix: str) -> list[str]:
    """Extract annotated public prototypes without exporting inline calls."""
    # Public detail headers also contain inline helpers. Calls inside those
    # helpers are not exports; require the declaration's API annotation.
    pattern = re.compile(r"\b[A-Z][A-Z0-9_]*_API\s+[^;{}]*?\b(" + prefix
                         + r"[A-Z]\w*)\s*\([^;{}]*\)\s*;", re.S)
    names = set()
    for header in headers:
        names.update(pattern.findall(without_comments(header)))
    if not names:
        raise ValueError(f"no public functions found for {prefix}")
    return sorted(names)


def public_functions(headers: list[Path], prefix: str) -> list[str]:
    return public_functions_text([p.read_text(encoding="utf-8") for p in headers], prefix)


def collect(source: Path) -> dict[str, tuple[Path, bytes]]:
    source = source.resolve(strict=True)
    files = {}

    def add(path: Path, target: str) -> None:
        if not path.resolve(strict=True).is_relative_to(source):
            raise ValueError(f"upstream path escapes source: {path}")
        files[target] = (path, path.read_bytes())

    for name in ("xrt.h", "xrt_decl.h"):
        add(source / "single" / name, "lib/" + name)
    # Inline wait helpers are shared by the modular extensions. They are real
    # upstream code, not declaration shims, and must retain their bytes.
    for path in sorted((source / "include/xrt/detail").rglob("*.h")):
        add(path, "lib/xrtshim/xrt/detail/" + path.relative_to(source / "include/xrt/detail").as_posix())
    for name in library_names(source / "extlibs"):
        base = source / "extlibs" / name
        # Older snapshots had flat TUs; current snapshots use manifest sources.
        root_files = {p.name for pattern in ("*.h", "*.c") for p in base.glob(pattern)}
        for relative in sorted(root_files | {"README.md", "LICENSE"}):
            path = base / relative
            if path.is_file():
                add(path, f"lib/{name}/{relative}")
        for directory in ("include", "src", "config"):
            for path in sorted((base / directory).rglob("*")):
                if path.is_file():
                    add(path, f"lib/{name}/" + path.relative_to(base).as_posix())
    return files


def generate_shims(declarations: str, header_names: list[str]) -> dict[str, bytes]:
    features = sorted(set(re.findall(r"XRT_DECLARATIONS_RESTORE_XRT_FEATURE_(\w+)", declarations)))
    if len(features) < 100:
        raise ValueError("incomplete xrt declaration feature inventory")
    lines = ["/* Generated by tools/sync_xrt.py from xrt_decl.h; repeatable include. */"]
    for name in features:
        lines += [f"#if (defined(XRT_MODULE_ALL) || defined(XRT_MODULE_{name})) && !defined(XRT_FEATURE_{name})",
                  f"#define XRT_FEATURE_{name}", "#endif"]
    output = {"lib/xrtshim/xrt/promote.h": ("\n".join(lines) + "\n").encode()}
    shim = b"/* Generated xrt modular header bridge. */\n#include <xrt/promote.h>\n#include <xrt_decl.h>\n"
    for name in header_names + ["xrt.h"]:
        output["lib/xrtshim/xrt/" + name] = shim
    return output


def modular_registry(source: Path, registry: dict) -> dict:
    """Derive native objects and the complete public SDK from upstream manifests.

    Native products compile as separate translation units. No copied single
    implementation or stale xs unity wrapper is allowed to hide missing APIs.
    Preserve xs's extension names and dependency selection contract.
    """
    libraries = library_names(source / "extlibs")
    manifests = {name: json.loads((source / "extlibs" / name / "config/modules.json")
                                 .read_text(encoding="utf-8")) for name in libraries}
    owners = {module["name"]: name for name, manifest in manifests.items()
              for module in manifest["modules"]}
    for name in libraries:
        base = source / "extlibs" / name
        manifest = manifests[name]
        prefix = f"extlibs/{name}/"

        def target(relative: str) -> str:
            if not relative.startswith(prefix):
                raise ValueError(f"{name}: manifest path outside product: {relative}")
            path = source / relative
            if not path.resolve(strict=True).is_relative_to(base.resolve()):
                raise ValueError(f"{name}: manifest path escapes product: {relative}")
            return "lib/" + relative.removeprefix("extlibs/")

        identifier = name.replace("-", "_").upper()
        entry = registry.setdefault(name, {
            "macro": "XS_USE_" + identifier,
            "symbols": f"src/script/import_{name.replace('-', '_')}.inc",
            "symbol_macro": "XS_" + identifier + "_SYMBOL",
        })
        headers = {p.relative_to(base / "include").as_posix():
                   "lib/" + p.relative_to(source / "extlibs").as_posix()
                   for p in sorted((base / "include").rglob("*.h"))}
        if not headers:
            raise ValueError(f"{name}: no public headers")
        # Retain the former flat TCC spelling for existing consumer scripts.
        if name == "xllm":
            headers["xllm-executor.h"] = headers["xllm/executor.h"]
        sources = sorted({target(p) for m in manifest["modules"] for p in m.get("sources", [])})
        if not sources:
            raise ValueError(f"{name}: no native sources")
        entry["headers"] = headers
        entry["sources"] = [{"path": p} for p in sources]
        # Upstream native builds select module features explicitly. In
        # particular the shared mail transport TUs do not include a protocol's
        # feature header before their gates; MODULE_ALL alone is insufficient.
        entry["feature_macro"] = ["XRT_MODULE_ALL", manifest["module_prefix"] + "ALL",
                                  *sorted({m["feature"] for m in manifest["modules"] if m.get("feature")})]
        entry["host_includes"] = [f"lib/{name}/include", "lib/xrtshim"]
        # dependency_manifests also contain test-only dependencies. Only
        # production feature/source modules determine the native closure.
        requires = sorted({owners[dependency] for module in manifest["modules"]
                           if module.get("feature") or module.get("sources")
                           for dependency in module.get("depends", [])
                           if dependency in owners and owners[dependency] != name})
        if requires:
            entry["requires"] = requires
        else:
            entry.pop("requires", None)
    return registry


def check_lock(root: Path = ROOT, lock: Path = LOCK) -> None:
    data = json.loads(lock.read_text(encoding="utf-8"))
    if data.get("schema") != 1 or not data.get("files"):
        raise ValueError("invalid xrt source lock")
    for relative, expected in data["files"].items():
        path = (root / relative).resolve()
        if not path.is_relative_to(root.resolve()) or not path.is_file():
            raise ValueError(f"missing or out-of-project locked file: {relative}")
        if digest(path.read_bytes()) != expected["sha256"]:
            raise ValueError(f"xrt snapshot drift: {relative}; sync again instead of patching vendor files")


def _snapshot_path(name: str) -> Path:
    """Git paths must also be safe on Windows (drives, ADS and backslashes)."""
    path = PurePosixPath(name)
    if (not path.parts or path.is_absolute() or "\\" in name or
            any(part in ("", ".", "..") or ":" in part for part in name.split("/"))):
        raise ValueError(f"unsafe committed source path: {name}")
    return Path(*path.parts)


def _export_commit(source: Path, commit: str, destination: Path) -> None:
    """Export raw Git blobs, ignoring dirty files, filters and export-subst.

    A fresh private destination prevents overwriting the checkout. No checkout,
    branch, worktree or index operation, and no upstream Python code is run.
    """
    listing = subprocess.check_output(
        ["git", "ls-tree", "-rz", "--full-tree", commit, "--",
         "single/xrt.h", "single/xrt_decl.h", "include/xrt", "extlibs"], cwd=source)
    entries = []
    for item in listing.split(b"\0"):
        if not item:
            continue
        metadata, name = item.split(b"\t", 1)
        mode, kind, oid = metadata.split(b" ")
        relative = _snapshot_path(name.decode("utf-8"))
        # Mirror collect's library trees; no tests, binaries or generated
        # single extlibs are needed to refresh the production SDK.
        parts = relative.parts
        if parts[0] == "extlibs" and not (
                len(parts) >= 4 and parts[2] in ("include", "src", "config") or
                len(parts) == 3 and (parts[2] in ("README.md", "LICENSE") or
                                    relative.suffix in (".c", ".h"))):
            continue
        if mode not in (b"100644", b"100755") or kind != b"blob":
            raise ValueError(f"committed source must be a regular file: {name!r}")
        entries.append((relative, oid))
    if not entries:
        raise ValueError("committed source snapshot is empty")
    destination.mkdir()  # Must not already exist, including as a symlink.
    with tempfile.TemporaryFile() as errors, subprocess.Popen(
            ["git", "cat-file", "--batch"], cwd=source, stdin=subprocess.PIPE,
            stdout=subprocess.PIPE, stderr=errors) as process:
        try:
            for relative, oid in entries:
                process.stdin.write(oid + b"\n")
                process.stdin.flush()
                header = process.stdout.readline(200).split()
                if len(header) != 3 or header[0] != oid or header[1] != b"blob":
                    raise ValueError(f"cannot read committed source blob: {relative}")
                remaining = int(header[2])
                if remaining < 0:
                    raise ValueError(f"invalid committed source size: {relative}")
                target = destination / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                with target.open("xb") as output:
                    while remaining:
                        data = process.stdout.read(min(65536, remaining))
                        if not data:
                            raise ValueError(f"truncated committed source blob: {relative}")
                        output.write(data)
                        remaining -= len(data)
                if process.stdout.read(1) != b"\n":
                    raise ValueError(f"invalid committed source separator: {relative}")
            process.stdin.close()
            if process.wait(timeout=30) != 0:
                errors.seek(0)
                raise ValueError(errors.read().decode("utf-8", errors="replace"))
        finally:
            if process.poll() is None:
                process.kill()
                process.wait(timeout=10)


def refresh_commit(source: Path, reference: str) -> None:
    source = source.resolve(strict=True)
    commit = subprocess.check_output(
        ["git", "rev-parse", "--verify", "--end-of-options", reference + "^{commit}"],
        cwd=source, text=True, encoding="utf-8").strip()
    if not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", commit):
        raise ValueError("invalid committed source identity")
    with tempfile.TemporaryDirectory(prefix="xs-xrt-commit-") as directory:
        snapshot = Path(directory) / "source"
        _export_commit(source, commit, snapshot)
        refresh(snapshot, committed=commit)


def refresh_library_commit(source: Path, reference: str, library: str) -> None:
    """Update one committed extension while preserving core/other libraries.

    Product SDKs may retain legacy companion ABIs. Every selected upstream blob
    records its own commit; the top-level commit continues to identify core.
    """
    check_lock()
    source = source.resolve(strict=True)
    commit = subprocess.check_output(
        ["git", "rev-parse", "--verify", "--end-of-options", reference + "^{commit}"],
        cwd=source, text=True, encoding="utf-8").strip()
    if not re.fullmatch(r"[0-9a-f]{40}|[0-9a-f]{64}", commit):
        raise ValueError("invalid committed source identity")
    registry = load_registry()
    if library not in registry or not re.fullmatch(r"[a-z][a-z0-9-]*", library):
        raise ValueError("unknown extension")
    with tempfile.TemporaryDirectory(prefix="xs-xrt-library-") as directory:
        snapshot = Path(directory) / "source"
        _export_commit(source, commit, snapshot)
        snapshot = snapshot.resolve(strict=True)
        if library not in library_names(snapshot / "extlibs"):
            raise ValueError("extension missing in committed source")
        files = {p: v for p, v in collect(snapshot).items() if p.startswith(f"lib/{library}/")}
        derived = modular_registry(snapshot, json.loads(json.dumps(registry)))
        registry[library] = derived[library]
        entry = registry[library]
        manifest = json.loads(files[f"lib/{library}/config/modules.json"][1])
        names = public_functions_text([files[p][1].decode("utf-8") for p in entry["headers"].values()],
                                      symbol_prefix(library, manifest))
        if library == "xllm-session":
            raise ValueError("companion ABI requires a full coordinated refresh")
        generated = {
            entry["symbols"]: ("/* Generated by tools/sync_xrt.py from public headers. */\n" +
                               "".join(f"{entry['symbol_macro']}({n})\n" for n in names)).encode(),
            REGISTRY.relative_to(ROOT).as_posix(): (json.dumps(registry, indent=1, ensure_ascii=False)+"\n").encode(),
            f"lib/{library}/UPSTREAM.txt": (f"Source: xrt extlibs/{library}\nSnapshot: {commit}\n"
                "Byte-for-byte committed extension snapshot; core and other libraries retain their own pins.\n"
                "Per-file source commits and SHA256 are recorded in ../xrt_sources.lock.json.\n").encode(),
        }
        record = json.loads(LOCK.read_text(encoding="utf-8"))
        obsolete = [p for p in record["files"] if p.startswith(f"lib/{library}/") and p not in files and p not in generated]
        for relative in obsolete:
            (ROOT / relative).unlink()
            del record["files"][relative]
        for relative, (path, data) in files.items():
            target = ROOT / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            record["files"][relative] = {"source": path.relative_to(snapshot).as_posix(),
                                         "sha256": digest(data), "upstream_commit": commit}
        for relative, data in generated.items():
            target = ROOT / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            record["files"][relative] = {"generated": True, "sha256": digest(data)}
        record.setdefault("library_commits", {})[library] = commit
        LOCK.write_text(json.dumps(record, indent=2, ensure_ascii=False)+"\n", encoding="utf-8", newline="\n")
    check_lock()
    print(f"Synced committed {library} at {commit}; core and companion ABIs preserved")


def refresh(source: Path, *, committed: str | None = None) -> None:
    source = source.resolve(strict=True)
    commit = committed or subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=source, text=True).strip()
    libraries = library_names(source / "extlibs")
    if not libraries:
        raise ValueError("upstream has no extension manifests")
    files = collect(source)
    generated = generate_shims(files["lib/xrt_decl.h"][1].decode("utf-8"),
                               [p.name for p in sorted((source / "include/xrt").glob("*.h"))])
    registry = modular_registry(source, load_registry())
    for name in libraries:
        entry = registry[name]
        headers = [files[p][1].decode("utf-8") for p in entry["headers"].values()]
        manifest = json.loads(files[f"lib/{name}/config/modules.json"][1])
        prefix = symbol_prefix(name, manifest)
        # Session headers repeat the companion estimators for consumers. Their
        # implementation/export belongs to xllm, a required dependency.
        names = public_functions_text(headers, prefix)
        if name == "xllm-session":
            companion = public_functions_text([files[p][1].decode("utf-8")
                for p in registry["xllm"]["headers"].values()], "xllm")
            names = sorted(set(names) - set(companion))
        text = "/* Generated by tools/sync_xrt.py from public headers. */\n"
        text += "".join(f"{entry['symbol_macro']}({n})\n" for n in names)
        generated[entry["symbols"]] = text.encode()
    # Do not copy a moving source snapshot. Recheck every captured file first.
    for path, data in files.values():
        if path.read_bytes() != data:
            raise ValueError(f"upstream changed during collection: {path}")
    if committed is None and subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=source, text=True).strip() != commit:
        raise ValueError("upstream commit changed during collection")
    # Object selection and feature gates are part of the same SDK snapshot.
    generated[REGISTRY.relative_to(ROOT).as_posix()] = (
        json.dumps(registry, indent=1, ensure_ascii=False) + "\n").encode("utf-8")
    status = "" if committed is not None else subprocess.check_output(
        ["git", "status", "--porcelain", "--", "single", "extlibs", "include/xrt"],
        cwd=source, text=True, encoding="utf-8")
    # Remove only files owned by the previous snapshot and verify their bytes
    # before changing anything. An edited vendor file requires an explicit
    # reconciliation, never silent deletion during an upstream refresh.
    obsolete = []
    if LOCK.is_file():
        check_lock()
        previous = json.loads(LOCK.read_text(encoding="utf-8"))["files"]
        obsolete = sorted(set(previous) - set(files) - set(generated) -
                          {"src/script/import_xrt.inc", "lib/xrt_version.txt"} -
                          {f"lib/{name}/UPSTREAM.txt" for name in libraries})
    for relative in obsolete:
        (ROOT / relative).unlink()
    for relative, (_, data) in files.items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for relative, data in generated.items():
        path = ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    version = commit + ("-working-tree" if status else "")
    version_text = version + "\nByte-for-byte upstream snapshot; file hashes in xrt_sources.lock.json.\nNo local upstream patches; refresh with python tools/sync_xrt.py --source ../xrt.\n"
    (ROOT / "lib/xrt_version.txt").write_text(version_text, encoding="utf-8", newline="\n")
    generated["lib/xrt_version.txt"] = version_text.encode()
    for name in libraries:
        relative = f"lib/{name}/UPSTREAM.txt"
        metadata = (f"Source: xrt extlibs/{name}\nSnapshot: {version}\n"
                    "Upstream source bytes and SHA256 are recorded in ../xrt_sources.lock.json.\n"
                    "Native sources, public headers and module configuration are vendored.\n"
                    "Native module sources compile separately; single-header implementations are not used.\n")
        (ROOT / relative).write_text(metadata, encoding="utf-8", newline="\n")
        generated[relative] = metadata.encode()
    import gen_xrt_symbols
    if gen_xrt_symbols.main() != 0:
        raise ValueError("xrt symbol generation failed")
    generated["src/script/import_xrt.inc"] = gen_xrt_symbols.OUTPUT.read_bytes()
    record = {"schema": 1, "upstream_commit": commit, "upstream_working_tree": bool(status), "files": {}}
    for relative, (path, data) in sorted(files.items()):
        record["files"][relative] = {"source": path.relative_to(source).as_posix(), "sha256": digest(data)}
    for relative, data in sorted(generated.items()):
        record["files"][relative] = {"generated": True, "sha256": digest(data)}
    LOCK.write_text(json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    check_lock()
    print(f"Synced {len(files)} upstream files at {version}; {len(generated)} generated integration files")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--source", type=Path)
    group.add_argument("--check", action="store_true")
    parser.add_argument("--ref", help="sync only raw files from this Git commit/ref, ignoring the working tree")
    parser.add_argument("--library", help="sync one committed extension, retaining core and other library pins")
    args = parser.parse_args()
    if args.ref is not None and args.source is None:
        parser.error("--ref requires --source")
    if args.library is not None and (args.ref is None or args.source is None):
        parser.error("--library requires --source and --ref")
    if args.check:
        check_lock()
        print("PASS xrt snapshot hashes")
    else:
        if args.library is not None:
            refresh_library_commit(args.source, args.ref, args.library)
        elif args.ref is not None:
            refresh_commit(args.source, args.ref)
        else:
            refresh(args.source)


if __name__ == "__main__":
    main()
